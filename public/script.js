const generatePreview = async (category) => {
  if (state.request) {
    state.request.abort();
  }

  state.request = new AbortController();
  const startedAt = performance.now();
  setButtonsDisabled(true);
  setStatus(t("statusGenerating"), true);
  setPreviewLoading(true, t("compilingTitle"), t("compilingSubtitle"));
  animateAgentTrace(buildPendingTrace("", "preview"));
  setLog("后端正在生成三文件 zip，并解压到预览目录...");

  try {
    setLog(t("backendGenerating"));
    const response = await fetch("/api/generate-preview", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ category, locale: currentLocale }),
      signal: state.request.signal
    });

    if (!response.ok) {
      throw new Error(`Preview generation failed: ${response.status}`);
    }

    const preview = await response.json();
    await waitForMinimumDuration(startedAt, GENERATION_MIN_MS);
    renderGeneratedPreview(preview);
  } catch (error) {
    if (error.name !== "AbortError") {
      stopAgentTraceAnimation();
      setPreviewLoading(false);
      setStatus(t("statusError"));
      setAgentTrace([traceLine("Agent", error.message, "error")], 0);
      setLog(error.message);
    }
  } finally {
    setButtonsDisabled(false);
    state.request = null;
  }
};

